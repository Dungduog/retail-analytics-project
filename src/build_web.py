"""Build the offline dashboard from published EDA tables and figures."""

import argparse
import csv
import json
from collections import Counter
from pathlib import Path
from shutil import copyfile


ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "reports" / "tables"
WEB = ROOT / "web"
EXAMPLE_INVOICES = {
    "581483": "C581484",
    "541431": "C541433",
}


def read_rows(path):
    with path.open(encoding="utf-8-sig", newline="") as source:
        yield from csv.DictReader(source)


def write_rows(name, columns, rows):
    with (TABLES / f"{name}.csv").open("w", encoding="utf-8", newline="") as output:
        writer = csv.writer(output, lineterminator="\n")
        writer.writerow(columns)
        writer.writerows(rows)


def export_web_tables(cleaned_file, customer_file):
    """Export the aggregates that are missing from the original EDA tables."""
    sales, cancelled = set(), set()
    country_quantity = Counter()
    examples = {}
    missing_customers = total_rows = 0
    for row in read_rows(cleaned_file):
        invoice = row["InvoiceNo"]
        quantity = int(row["Quantity"])
        total_rows += 1
        missing_customers += not row["CustomerID"]
        if row["IsCancelled"] == "True":
            cancelled.add(invoice)
        else:
            sales.add(invoice)
            country_quantity[row["Country"]] += quantity
        if invoice in EXAMPLE_INVOICES or invoice in EXAMPLE_INVOICES.values():
            examples[invoice] = row

    segments = Counter(row["Segment"] for row in read_rows(customer_file))
    write_rows("dashboard_summary", ("SalesInvoices", "CancelledInvoices", "MissingCustomerRows", "Rows"),
               [(len(sales), len(cancelled), missing_customers, total_rows)])
    write_rows("dashboard_country_quantity", ("Country", "Quantity"), sorted(country_quantity.items()))
    write_rows("dashboard_segments", ("Segment", "Customers"), segments.most_common())

    cases = []
    for invoice, cancellation in EXAMPLE_INVOICES.items():
        sale, refund = examples.get(invoice), examples.get(cancellation)
        if (sale and refund and sale["StockCode"] == refund["StockCode"]
                and int(sale["Quantity"]) == -int(refund["Quantity"])):
            cases.append((invoice, cancellation, sale["Description"].strip(),
                          sale["Quantity"], round(float(sale["Revenue"]), 2)))
    write_rows("dashboard_cancelled_orders", ("InvoiceNo", "Cancellation", "Description", "Quantity", "Revenue"), cases)


def load_table(name, **numeric_columns):
    rows = list(read_rows(TABLES / f"{name}.csv"))
    for row in rows:
        for column, converter in numeric_columns.items():
            row[column] = converter(row[column])
    return rows


def build_web():
    """Generate the local script and copy the chart used by the HTML."""
    data = {
        "summary": load_table("dashboard_summary", SalesInvoices=int, CancelledInvoices=int,
                              MissingCustomerRows=int, Rows=int)[0],
        "monthly": load_table("monthly_revenue", Revenue=float),
        "productQuantity": load_table("top_products_quantity", Quantity=int)[:10],
        "productRevenue": load_table("top_products_revenue", Revenue=float)[:10],
        "countryRevenue": load_table("country_revenue", Revenue=float),
        "countryQuantity": sorted(load_table("dashboard_country_quantity", Quantity=int),
                                  key=lambda row: row["Quantity"], reverse=True)[:10],
        "segments": load_table("dashboard_segments", Customers=int),
        "cancellations": load_table("dashboard_cancelled_orders", Quantity=int, Revenue=float),
        "refundFrequency": load_table("cancelled_products", CancelledInvoiceCount=int)[:3],
        "refundValue": load_table("cancelled_products_by_value", CancelledValue=float)[:3],
    }
    figures = WEB / "assets" / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    filename = "rfm_scatter_freq_monetary.png"
    copyfile(ROOT / "reports" / "figures" / filename, figures / filename)
    payload = json.dumps(data, ensure_ascii=False, allow_nan=False, indent=2)
    (WEB / "data.js").write_text(
        f"// Generated by src/build_web.py.\nwindow.RETAIL_DATA = {payload};\n", encoding="utf-8"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-tables", action="store_true", help="Refresh aggregates from processed CSVs first")
    if parser.parse_args().refresh_tables:
        processed = ROOT / "data" / "processed"
        export_web_tables(processed / "cleaned_retail.csv", processed / "customer_segments.csv")
    build_web()
